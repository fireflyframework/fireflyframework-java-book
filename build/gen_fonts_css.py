"""Generate theme/fonts.css: self-contained @font-face rules for the book fonts.

TEXT font = **Maven Pro** (SIL OFL). CODE font = **JetBrains Mono** (SIL OFL).
Both are embedded as base64 ``data:`` URIs so the SAME stylesheet renders the
fonts in BOTH targets with no path or bundling dependency:

  * the WeasyPrint PDF  (book.py passes theme/fonts.css to WeasyPrint), and
  * the EPUB3 package   (book.py concatenates theme/fonts.css into the EPUB CSS).

cairosvg (cover + openers) resolves the SAME families by name from
~/Library/Fonts, so install copies there too (see the build instructions).

Static TrueType weights live in theme/fonts/. Run after refreshing them:

    build/.venv/bin/python build/gen_fonts_css.py   (writes theme/fonts.css)
"""
from __future__ import annotations
import base64
from pathlib import Path

THEME = Path(__file__).resolve().parents[1] / "theme"
FONTS = THEME / "fonts"

# (file, css family, font-weight, font-style). Weights 500/600 carry the legacy
# "Maven Pro Medium"/"SemiBold" name-table families, so we pin them to the
# canonical "Maven Pro" family + explicit weight here — no fontconfig guessing.
FACES = [
    ("MavenPro-400.ttf",          "Maven Pro",      400, "normal"),
    ("MavenPro-500.ttf",          "Maven Pro",      500, "normal"),
    ("MavenPro-600.ttf",          "Maven Pro",      600, "normal"),
    ("MavenPro-700.ttf",          "Maven Pro",      700, "normal"),
    ("JetBrainsMono-Regular.ttf", "JetBrains Mono", 400, "normal"),
    ("JetBrainsMono-Bold.ttf",    "JetBrains Mono", 700, "normal"),
    ("JetBrainsMono-Italic.ttf",  "JetBrains Mono", 400, "italic"),
]


def build_css() -> str:
    lines = [
        "/* fonts.css — self-contained @font-face rules with base64-embedded TrueType.",
        "   GENERATED by build/gen_fonts_css.py from theme/fonts/*.ttf — do not edit by hand.",
        "   Embedding the TTFs as data: URIs makes the SAME CSS render the fonts in BOTH",
        "   the WeasyPrint PDF and the EPUB3 package with no path/bundling dependency.",
        "   TEXT font = Maven Pro (SIL OFL); CODE font = JetBrains Mono (SIL OFL). */",
        "",
    ]
    for fn, fam, wght, style in FACES:
        path = FONTS / fn
        if not path.exists():
            raise SystemExit(f"missing font file: {path}")
        b64 = base64.b64encode(path.read_bytes()).decode("ascii")
        lines.append(
            f'@font-face{{font-family:"{fam}";font-style:{style};font-weight:{wght};'
            f'font-display:swap;'
            f'src:url(data:font/ttf;base64,{b64}) format("truetype");}}'
        )
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    css = build_css()
    out = THEME / "fonts.css"
    out.write_text(css, encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes) from {len(FACES)} font face(s)")


if __name__ == "__main__":
    main()
